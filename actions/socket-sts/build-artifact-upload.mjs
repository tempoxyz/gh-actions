// Bundle the official GitHub artifact client so the post action needs neither
// a package-manager install nor an untrusted network download at runtime.
//
// npm ci --ignore-scripts && npm run build
// npm ci --ignore-scripts && npm run check
import { build } from "esbuild";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outfile = join(here, "dist", "artifact-upload.cjs");
const check = process.argv.includes("--check");
const version = (pkg) => JSON.parse(readFileSync(join(here, "node_modules", pkg, "package.json"), "utf8")).version;
const artifactVersion = version("@actions/artifact");
const esbuildVersion = version("esbuild");
const banner = [
  `// @actions/artifact ${artifactVersion}, bundled by esbuild ${esbuildVersion}.`,
  "// Generated by build-artifact-upload.mjs; do not edit.",
  "// Rebuild with `npm ci --ignore-scripts && npm run build`.",
].join("\n");
const result = await build({
  entryPoints: [join(here, "artifact-upload-entry.mjs")],
  bundle: true,
  format: "cjs",
  platform: "node",
  target: "node24",
  legalComments: "none",
  banner: { js: banner },
  write: false,
  logLevel: "warning",
});
const text = result.outputFiles[0].text;
if (check) {
  let current = "";
  try { current = readFileSync(outfile, "utf8"); } catch {}
  if (current !== text) {
    console.error(`::error::${outfile} is stale; rebuild and commit dist/artifact-upload.cjs`);
    process.exit(1);
  }
  console.log(`ok: artifact uploader matches @actions/artifact ${artifactVersion}`);
} else {
  mkdirSync(dirname(outfile), { recursive: true });
  writeFileSync(outfile, text);
  console.log(`wrote ${outfile}`);
}
